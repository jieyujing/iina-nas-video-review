#!/usr/bin/env python3
"""Create a minimal IINA plugin staging directory from a verified Parcel build.

Intentionally excludes node_modules, test fixtures, upstream demo assets and source
files. This is a local development package, not a production release.
"""
from pathlib import Path
import json
import shutil

ROOT=Path(__file__).resolve().parents[1]
STAGE=ROOT/"release-staging"
BUILD=ROOT/"dist"

if not (BUILD/"index.js").is_file() or not (BUILD/"ui/sidebar/index.html").is_file():
    raise SystemExit("Parcel build missing: run npm run build first")
if STAGE.exists():
    if not (STAGE/".development-staging").exists():
        raise SystemExit("Refusing to replace non-generated staging directory")
    shutil.rmtree(STAGE)
STAGE.mkdir()
for name in ("Info.json","LICENSE","THUMBNAILS_MIT_LICENSE.md","UPSTREAM.md","pref.html"):
    shutil.copy2(ROOT/name,STAGE/name)
shutil.copytree(BUILD,STAGE/"dist")
(STAGE/".development-staging").write_text(
    "Generated by scripts/package_dev.py; safe to regenerate.\n"
)
info=json.loads((STAGE/"Info.json").read_text())
for key in ("entry","globalEntry","preferencesPage"):
    target=STAGE/info[key]
    if not target.is_file():
        raise SystemExit(f"Missing packaged resource: {key} -> {target}")
if not (STAGE/"dist/ui/sidebar/index.html").is_file():
    raise SystemExit("Missing sidebar HTML entrypoint")
files=[str(f.relative_to(STAGE)) for f in STAGE.rglob("*") if f.is_file()]
print(json.dumps({
    "plugin":info["identifier"],"version":info["version"],
    "staging":str(STAGE),"file_count":len(files),
    "files":files
},indent=2))
